import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import { CommitteeSettings, Member, Receipt } from '../types/maa';
import { formatDateIN, formatMonthLabel, paiseToRupees } from './chandaEngine';
import { PAYMENT_METHOD_LABELS } from './i18n';

function pdfINR(paise: number): string {
  const rupees = paiseToRupees(paise);
  return `Rs. ${new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: paise % 100 !== 0 ? 2 : 0,
    maximumFractionDigits: 2,
  }).format(rupees)}`;
}

export function downloadReceiptPDF(receipt: Receipt, settings: CommitteeSettings) {
  const doc = new jsPDF({ unit: 'pt', format: 'a5', orientation: 'portrait' });
  const pageWidth = doc.internal.pageSize.getWidth();

  // Deep Navy Header Band
  doc.setFillColor(15, 33, 67);
  doc.rect(0, 0, pageWidth, 86, 'F');

  // Saffron accent rule
  doc.setFillColor(217, 93, 22);
  doc.rect(0, 86, pageWidth, 4, 'F');

  // Header text
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('MAA — Monthly Association Account', 24, 34);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(settings.committeeName || 'Puja Committee', 24, 52, { maxWidth: pageWidth - 48 });
  doc.text(settings.committeeAddress || '', 24, 68, { maxWidth: pageWidth - 48 });

  // Receipt Title & Number
  doc.setTextColor(15, 33, 67);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('OFFICIAL CHANDA RECEIPT', 24, 114);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  doc.text(`Receipt No: ${receipt.receiptNumber}`, 24, 132);
  doc.text(`Date: ${formatDateIN(receipt.paymentDate)}`, pageWidth - 24, 132, { align: 'right' });

  if (receipt.status === 'VOID') {
    doc.setTextColor(220, 38, 38);
    doc.setFont('helvetica', 'bold');
    doc.text('VOID / REVERSED', pageWidth - 24, 114, { align: 'right' });
  }

  const rows = [
    ['Member Name', receipt.memberName],
    ['Member ID', receipt.memberCode],
    ['Mobile Number', receipt.mobile || '—'],
    ['Collection Month', formatMonthLabel(receipt.monthKey, 'en')],
    ['Payment Method', PAYMENT_METHOD_LABELS[receipt.paymentMethod]?.en || receipt.paymentMethod],
    ['Transaction Ref', receipt.transactionRef || '—'],
    ['Amount Paid', pdfINR(receipt.amountPaise)],
    ['Previous Due', pdfINR(receipt.previousDuePaise)],
    ['Remaining Due', pdfINR(receipt.remainingDuePaise)],
    ['Advance Balance', pdfINR(receipt.advanceBalancePaise)],
    ['Collected By', receipt.collectorName],
  ];

  autoTable(doc, {
    startY: 148,
    margin: { left: 24, right: 24 },
    theme: 'grid',
    styles: {
      fontSize: 9.5,
      cellPadding: 6,
      textColor: [15, 23, 42],
      lineColor: [226, 232, 240],
    },
    columnStyles: {
      0: { fontStyle: 'bold', cellWidth: 135, fillColor: [248, 250, 252] },
      1: { cellWidth: 'auto' },
    },
    body: rows,
  });

  const finalY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 450;
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text('Every Contribution Matters. Thank you for supporting our Puja Committee.', 24, finalY + 26);
  doc.text(`Generated by MAA System · ${settings.contactNumber || ''}`, 24, finalY + 40);

  doc.save(`${receipt.receiptNumber}.pdf`);
}

export function exportReportExcel(
  filename: string,
  sheetName: string,
  headers: string[],
  rows: Array<Array<string | number>>
) {
  const worksheet = XLSX.utils.aoa_to_sheet([headers, ...rows]);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, sheetName.slice(0, 31));
  XLSX.writeFile(workbook, `${filename}.xlsx`);
}

export function exportReportCSV(
  filename: string,
  headers: string[],
  rows: Array<Array<string | number>>
) {
  const escape = (val: string | number) => {
    const s = String(val ?? '');
    if (s.includes(',') || s.includes('"') || s.includes('\n')) {
      return `"${s.replace(/"/g, '""')}"`;
    }
    return s;
  };
  const csv = [headers.map(escape).join(','), ...rows.map((r) => r.map(escape).join(','))].join('\n');
  const blob = new Blob(['\uFEFF' + csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${filename}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportReportPDF(
  filename: string,
  title: string,
  subtitle: string,
  headers: string[],
  rows: Array<Array<string | number>>
) {
  const doc = new jsPDF({ orientation: headers.length > 6 ? 'landscape' : 'portrait', unit: 'pt', format: 'a4' });
  doc.setFillColor(15, 33, 67);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 56, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(`MAA — ${title}`, 28, 28);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(subtitle, 28, 44);

  autoTable(doc, {
    startY: 72,
    head: [headers],
    body: rows.map((r) => r.map((c) => String(c ?? ''))),
    styles: { fontSize: 8.5, cellPadding: 5 },
    headStyles: { fillColor: [15, 33, 67], textColor: [255, 255, 255] },
    alternateRowStyles: { fillColor: [248, 250, 252] },
  });

  doc.save(`${filename}.pdf`);
}

export async function parseMembersSpreadsheet(file: File): Promise<
  Array<{
    fullName: string;
    mobile: string;
    whatsappNumber?: string;
    address?: string;
    area?: string;
    monthlyChandaRupees: number;
    category: Member['category'];
    whatsappConsent: boolean;
  }>
> {
  const buf = await file.arrayBuffer();
  const wb = XLSX.read(buf, { type: 'array' });
  const firstSheet = wb.Sheets[wb.SheetNames[0]];
  const jsonRows = XLSX.utils.sheet_to_json<Record<string, unknown>>(firstSheet);

  return jsonRows
    .map((row) => {
      const fullName = String(row['Full Name'] || row['fullName'] || row['Name'] || '').trim();
      const mobile = String(row['Mobile'] || row['mobile'] || row['Phone'] || '').trim();
      const whatsappNumber = String(row['WhatsApp'] || row['whatsappNumber'] || mobile).trim();
      const area = String(row['Area'] || row['area'] || row['Locality'] || '').trim();
      const address = String(row['Address'] || row['address'] || '').trim();
      const amountRaw = Number(row['Monthly Chanda'] || row['monthlyChanda'] || row['Amount'] || 500);
      const catRaw = String(row['Category'] || row['category'] || 'GENERAL').toUpperCase();
      const category: Member['category'] = ['GENERAL', 'PATRON', 'SENIOR', 'YOUTH', 'FAMILY'].includes(catRaw)
        ? (catRaw as Member['category'])
        : 'GENERAL';
      const consentRaw = String(row['WhatsApp Consent'] || row['whatsappConsent'] || 'true').toLowerCase();
      const whatsappConsent = consentRaw === 'true' || consentRaw === 'yes' || consentRaw === '1';

      return {
        fullName,
        mobile,
        whatsappNumber,
        address,
        area,
        monthlyChandaRupees: Number.isFinite(amountRaw) && amountRaw >= 0 ? amountRaw : 500,
        category,
        whatsappConsent,
      };
    })
    .filter((m) => m.fullName.length > 0 && m.mobile.length >= 10);
}
